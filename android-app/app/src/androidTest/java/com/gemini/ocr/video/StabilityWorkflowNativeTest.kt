    @Test(timeout = 90_000L)
    fun nonSeekableDocumentsImportAcrossMultipleSelectionsAndRejectOneBadFile(): Unit = runBlocking {
        val context = guard()
        evidence(context, "pipe-import") { report, sample ->
            context.contentResolver.openFileDescriptor(uri("EP01.mp4"), "r")!!.use { descriptor ->
                try { Os.lseek(descriptor.fileDescriptor, 0, OsConstants.SEEK_SET); fail("Fixture must be a pipe") }
                catch (error: ErrnoException) { assertEquals(OsConstants.ESPIPE, error.errno) }
            }
            val direct = VideoJobs.get(context).create(uri("EP01.mp4"), "Direct pipe import")
            assertTrue(direct.durationMs > 0 && direct.width > 0 && direct.height > 0)
            assertEquals("file", Uri.parse(direct.uri).scheme)
            assertEquals(uri("EP01.mp4").toString(), direct.originalSourceUri)
            assertNotNull(VideoDecoder.preview(context, Uri.parse(direct.uri), 500)?.also { it.recycle() })
            sample()

            val jobs = BatchJobs.get(context)
            val batch = jobs.create("Native pipe selection audit", BatchKind.SERIES)
            val first = jobs.add(batch.id, listOf(uri("EP02.mp4"), uri("broken.mp4"), uri("EP01.mp4")))
            assertEquals(listOf("EP01.mp4", "EP02.mp4"), first.items.map { it.name })
            assertTrue(first.message.contains("broken.mp4"))
            val second = jobs.add(batch.id, listOf(uri("EP03.mp4"), uri("EP02.mp4")))
            assertEquals(listOf("EP01.mp4", "EP02.mp4", "EP03.mp4"), second.items.map { it.name })
            assertEquals(first.items.map { it.projectId }, second.items.take(2).map { it.projectId })
            val videos = VideoStore(context)
            second.items.forEach { item ->
                val project = videos.load(item.projectId)
                assertEquals("file", Uri.parse(project.uri).scheme)
                assertEquals(batch.id, File(videos.folder(project.id), "batch-owner").readText())
                assertEquals(0, project.cloudCalls)
            }
            val restored = BatchStore(context).load(batch.id)
            assertEquals(second.items.map { it.projectId }, restored.items.map { it.projectId })
            report.put("batchId", batch.id).put("realPipeVerified", true)
                .put("retainedPrivateFile", true).put("acceptedVideos", second.items.size)
                .put("rejectedVideos", 1).put("duplicateAdded", false)
            sample()
        }
    }

    @Test(timeout = 240_000L)
    fun foregroundBatchPausesTwiceReopensCheckpointAndExportsApprovedFixture(): Unit = runBlocking {
        Log.i("StabilityNative", "service-resume:guard-start")
        val context = guard()
        Log.i("StabilityNative", "service-resume:guard-complete")
        val jobs = BatchJobs.get(context)
        try {
            evidence(context, "service-resume") { report, sample ->
                phase(report, "create-batch")
                val batch = jobs.create("Native service checkpoint audit", BatchKind.SERIES)
                phase(report, "import-pipe")
                jobs.add(batch.id, listOf(uri("EP01.mp4")))
                phase(report, "configure-batch")
                jobs.configure(batch.id, VideoTranslationMode.OFFLINE, VideoSourceMode.SIDECAR)
                val videos = VideoStore(context)
                val item = BatchStore(context).load(batch.id).items.single()
                val original = videos.load(item.projectId)
                val cue = VideoCue("approved-native-fixture", 1_000, 3_000, "你好", "Xin chào Việt Nam",
                    approved = true, model = "manual-native-fixture", origin = "MANUAL_TEST_FIXTURE")
                videos.save(original.copy(cues = listOf(cue), scanMs = original.durationMs,
                    stage = VideoStage.REVIEW, resumeStage = VideoStage.EXPORTING, model = "manual-native-fixture"))
                val sourceHash = sha256(File(Uri.parse(original.uri).path!!))
                // Deterministic resource gate only. No capture, projection, network or AI is started.
                SessionState.running.value = true
                repeat(2) {
                    phase(report, "open-activity-cycle-$it")
                    ActivityScenario.launch<BatchActivity>(Intent(context, BatchActivity::class.java)).use { scenario ->
                        phase(report, "start-service-cycle-$it")
                        scenario.onActivity { jobs.start(batch.id) }
                        await { videos.load(item.projectId).stage == VideoStage.WAITING_LIVE }
                        assertEquals(batch.id, VideoJobs.get(context).batchBusy.value)
                        sample()
                        phase(report, "pause-service-cycle-$it")
                        scenario.onActivity { jobs.pause() }
                        await { jobs.busy.value == null && VideoJobs.get(context).busy.value == null }
                        val saved = VideoStore(context).load(item.projectId)
                        assertEquals(VideoStage.PAUSED, saved.stage)
                        assertEquals(VideoStage.EXPORTING, saved.resumeStage)
                        assertEquals(listOf(cue), saved.cues)
                        assertEquals(original.durationMs, saved.scanMs)
                        assertEquals("PAUSED", BatchStore(context).load(batch.id).state)
                    }
                    assertFalse(SessionState.batchActivityVisible.value)
                    jobs.refresh()
                    assertEquals("PAUSED", jobs.batches.value.single { it.id == batch.id }.state)
                }
                SessionState.running.value = false
                phase(report, "open-final-export-activity")
                ActivityScenario.launch<BatchActivity>(Intent(context, BatchActivity::class.java)).use { scenario ->
                    phase(report, "start-final-export")
                    scenario.onActivity { jobs.start(batch.id) }
                    await(180_000L) { jobs.busy.value == null && VideoJobs.get(context).busy.value == null }
                }
                val finished = BatchStore(context).load(batch.id)
                phase(report, "verify-final-export")
                assertEquals(finished.message, "REVIEW", finished.state)
                assertEquals(1, finished.outputs.size)
                val saved = videos.load(item.projectId)
                assertEquals(0, saved.cloudCalls)
                assertEquals(listOf(cue), saved.cues)
                assertTrue(File(saved.exportedMp4).length() > 0)
                assertNotNull(VideoDecoder.preview(context, Uri.fromFile(File(saved.exportedMp4)), 2_000)?.also { it.recycle() })
                assertEquals(sourceHash, sha256(File(Uri.parse(original.uri).path!!)))
                report.put("batchId", batch.id).put("pauseResumeCycles", 2)
                    .put("activityReopenCycles", 2).put("checkpointPreserved", true)
                    .put("approvedTextSeeded", true).put("realExportDecoded", true)
                    .put("exportElapsedMs", saved.exportElapsedMs).put("workerMaxPssKiB", saved.maxPssKiB)
                sample()
            }
        } finally {
            SessionState.running.value = false
            if (jobs.busy.value != null) jobs.pause()
        }
    }

    @Test(timeout = 60_000L)
    fun validVideoWithoutEmbeddedSubtitlesDoesNotInventSourceCues(): Unit = runBlocking {
        val context = guard()
        evidence(context, "no-embedded-subtitles") { report, sample ->
            val project = VideoJobs.get(context).create(uri("EP01.mp4"), "No embedded subtitle fixture")
            val tracks = VideoSubtitles.embedded(context, Uri.parse(project.uri), project.durationMs, probeOnly = true)
            assertTrue(tracks.first.isEmpty() && tracks.second.isEmpty())
            var failure: Exception? = null
            try { VideoSubtitles.embedded(context, Uri.parse(project.uri), project.durationMs) }
            catch (error: IllegalArgumentException) { failure = error }
            assertNotNull("No embedded text must produce an actionable error", failure)
            assertTrue(failure!!.message.orEmpty().contains("Không có phụ đề văn bản"))
            val saved = VideoStore(context).load(project.id)
            assertTrue(saved.cues.isEmpty())
            assertEquals(0, saved.cloudCalls)
            report.put("embeddedTextTracks", 0).put("inventedCues", 0).put("rejectedWithoutApi", true)
            sample()
        }
    }

    private suspend fun await(timeout: Long = 20_000L, predicate: () -> Boolean) {
        withTimeout(timeout) { while (!predicate()) delay(100) }
    }
    private fun phase(report: JSONObject, value: String) {
        report.put("phase", value)
        Log.i("StabilityNative", value)
    }
    private suspend fun evidence(context: Context, name: String, test: suspend (JSONObject, () -> Unit) -> Unit) {
        val fixtures = File(checkNotNull(context.getExternalFilesDir(null)), "movie-fixtures").apply { mkdirs() }
        val report = JSONObject().put("schema", 1).put("completed", false).put("cloudCalls", 0)
            .put("scope", "Native synthetic $name; no fresh OCR/translation or real cloud integration")
        val started = SystemClock.elapsedRealtime()
        var maxPss = 0
        fun sample() { val info = Debug.MemoryInfo(); Debug.getMemoryInfo(info); maxPss = maxOf(maxPss, info.totalPss) }
        try { sample(); test(report, ::sample); report.put("completed", true) }
        catch (error: Throwable) { report.put("failureType", error.javaClass.simpleName); throw error }
        finally {
            sample()
            report.put("elapsedMs", SystemClock.elapsedRealtime() - started).put("sampledPeakPssKiB", maxPss)
            File(fixtures, "stability-$name-${UUID.randomUUID()}.json").writeText(report.toString(2))
        }
    }
    private fun sha256(file: File): String {
        val digest = MessageDigest.getInstance("SHA-256")
        file.inputStream().use { input -> val buffer = ByteArray(128 * 1024); while (true) { val read = input.read(buffer); if (read < 0) break; digest.update(buffer, 0, read) } }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }
    private fun guard(): Context {
        assumeTrue(InstrumentationRegistry.getArguments().getString("executeStabilityAudit") == "true")
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        require(BuildConfig.DEBUG && context.packageName == "com.gemini.ocr.codexbench")
        require(BuildConfig.VERIFICATION_OFFLINE_NETWORK && BuildConfig.GEMINI_API_KEY.isEmpty())
        assertEquals(PackageManager.PERMISSION_DENIED, context.checkSelfPermission(Manifest.permission.INTERNET))
        require(!SessionState.running.value && VideoJobs.get(context).busy.value == null && BatchJobs.get(context).busy.value == null)
        require(VideoCloudSync.get(context).state.value.accountEmail.isBlank())
        return context
    }
